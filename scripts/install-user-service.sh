#!/usr/bin/env bash
# Install MemoGarden as a user-session systemd service (PRD: Process Model
# and Service Units — user-session mode).
#
# Semantics (deliberate, see PRD):
#   - starts at login, shuts down at logout (WantedBy=default.target)
#   - NO lingering by default; surviving logout is appliance mode's job
#   - no root, no dedicated system user; XDG paths per RFC-004 `run` verb
#
# Usage:
#   install-user-service.sh install [--bind HOST:PORT] [--with-ingest-timer]
#                                   [--ingest-account EMAIL] [--ingest-limit N]
#   install-user-service.sh uninstall
#   install-user-service.sh status
#
# The server binds 127.0.0.1:8600 by default — NOT 8080, which belongs to
# the OAuth consent callback server, and NOT 5000, the dev server's port.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(dirname "$SCRIPT_DIR")"

COMMAND="${1:-install}"
shift || true

BIND="127.0.0.1:8600"
WITH_INGEST_TIMER=0
INGEST_ACCOUNT=""
INGEST_LIMIT=10

API_DIR="$REPO_ROOT/memogarden-api"
API_VENV="$API_DIR/.venv"
INGEST_VENV="$REPO_ROOT/providers/gmail-importer/.venv"

UNIT_DIR="$HOME/.config/systemd/user"
STATE_DIR="$HOME/.local/state/memogarden/logs"
DATA_DIR="$HOME/.local/share/memogarden"

while [ $# -gt 0 ]; do
    case "$1" in
        --bind) BIND="$2"; shift 2 ;;
        --with-ingest-timer) WITH_INGEST_TIMER=1; shift ;;
        --ingest-account) INGEST_ACCOUNT="$2"; shift 2 ;;
        --ingest-limit) INGEST_LIMIT="$2"; shift 2 ;;
        *) echo "Unknown option: $1" >&2; exit 2 ;;
    esac
done

fail() { echo "ERROR: $*" >&2; exit 1; }

do_install() {
    [ -x "$API_VENV/bin/gunicorn" ] || fail \
        "gunicorn not found at $API_VENV/bin/gunicorn — run 'poetry install' in memogarden-api first"
    if [ "$WITH_INGEST_TIMER" = 1 ]; then
        [ -n "$INGEST_ACCOUNT" ] || fail "--with-ingest-timer requires --ingest-account"
        [ -x "$INGEST_VENV/bin/python" ] || fail \
            "gmail-importer venv not found at $INGEST_VENV — run 'poetry install' in providers/gmail-importer first"
    fi

    mkdir -p "$UNIT_DIR" "$STATE_DIR" "$DATA_DIR"

    # ---- memogarden.service (the persistent server backend) ----
    cat > "$UNIT_DIR/memogarden.service" <<UNIT
# MemoGarden user-session server. Generated by scripts/install-user-service.sh;
# edits here are overwritten on reinstall.
[Unit]
Description=MemoGarden personal server (user session)
After=network.target

[Service]
Type=simple
ExecStart=$API_VENV/bin/gunicorn --config $API_DIR/gunicorn.conf.py --chdir $API_DIR api.main:app
Environment=MEMOGARDEN_VERB=run
Environment=MEMOGARDEN_BIND=$BIND
Environment=MEMOGARDEN_PID_FILE=%t/memogarden/memogarden.pid
Environment=MEMOGARDEN_ACCESS_LOG=$STATE_DIR/access.log
Environment=MEMOGARDEN_ERROR_LOG=$STATE_DIR/error.log
Environment=MEMOGARDEN_WORKERS=1
WorkingDirectory=$DATA_DIR
RuntimeDirectory=memogarden
Restart=on-failure
RestartSec=5

[Install]
WantedBy=default.target
UNIT

    if [ "$WITH_INGEST_TIMER" = 1 ]; then
        cat > "$UNIT_DIR/memogarden-ingest.service" <<UNIT
# MemoGarden scheduled email ingestion, three idempotent passes:
#   next        progressive backfill of the oldest-first window (tracks a
#               cursor; becomes a no-op once the window is fully ingested —
#               the switchover point to...)
#   incremental historyId sync of NEW mail since the stored historyId
#               (seeds on first run; delivers new mail hourly)
#   attachments binary extraction for everything newly ingested.
# Serves from the search cache (refreshed 6-hourly).
[Unit]
Description=MemoGarden scheduled email ingestion

[Service]
Type=oneshot
WorkingDirectory=$DATA_DIR
ExecStart=$INGEST_VENV/bin/python -m gmail_importer.ingest --account $INGEST_ACCOUNT next --limit $INGEST_LIMIT --quiet
ExecStart=$INGEST_VENV/bin/python -m gmail_importer.ingest --account $INGEST_ACCOUNT incremental --limit $INGEST_LIMIT --quiet
ExecStart=$INGEST_VENV/bin/python -m gmail_importer.ingest --account $INGEST_ACCOUNT attachments --quiet
UNIT

        cat > "$UNIT_DIR/memogarden-ingest.timer" <<'UNIT'
# Session-scoped hourly trigger: fires only while the user is logged in
# (no Persistent catch-up — that would defeat the login/logout lifecycle).
[Unit]
Description=Run MemoGarden email ingestion hourly

[Timer]
OnCalendar=hourly
AccuracySec=5min
Persistent=false
Unit=memogarden-ingest.service

[Install]
WantedBy=timers.target
UNIT
    fi

    systemctl --user daemon-reload
    systemctl --user enable --now memogarden.service
    if [ "$WITH_INGEST_TIMER" = 1 ]; then
        systemctl --user enable --now memogarden-ingest.timer
    fi

    # Health check
    PORT="${BIND##*:}"
    printf "Waiting for %s/health" "$BIND"
    for _ in $(seq 1 20); do
        if curl -sf --max-time 2 "http://$BIND/health" >/dev/null 2>&1; then
            echo " — healthy"
            break
        fi
        printf "."
        sleep 1
    done
    if ! curl -sf --max-time 2 "http://$BIND/health" >/dev/null 2>&1; then
        echo " — NOT responding; check: journalctl --user -u memogarden.service -n 30" >&2
        exit 1
    fi

    echo
    echo "Installed:"
    echo "  memogarden.service            -> http://$BIND  (XDG data: $DATA_DIR)"
    if [ "$WITH_INGEST_TIMER" = 1 ]; then
        echo "  memogarden-ingest.timer       -> hourly, account $INGEST_ACCOUNT, limit $INGEST_LIMIT"
    fi
    echo
    echo "Lifecycle (per PRD): starts at login, stops at logout."
    echo "  Lingering is NOT enabled; for appliance-like availability opt in yourself:"
    echo "    loginctl enable-linger"
    echo "  Uninstall: $0 uninstall"
}

do_uninstall() {
    systemctl --user disable --now memogarden-ingest.timer 2>/dev/null || true
    systemctl --user disable --now memogarden.service 2>/dev/null || true
    rm -f "$UNIT_DIR/memogarden.service" "$UNIT_DIR/memogarden-ingest.service" "$UNIT_DIR/memogarden-ingest.timer"
    systemctl --user daemon-reload
    echo "Uninstalled user units. Data ($DATA_DIR) and logs ($STATE_DIR) left in place."
}

do_status() {
    systemctl --user --no-pager status memogarden.service | head -8 || true
    systemctl --user --no-pager list-timers memogarden-ingest.timer 2>/dev/null | head -4 || true
    PORT="${BIND##*:}"
    curl -sf --max-time 3 "http://$BIND/health" && echo " <- http://$BIND/health" || echo "health: no response on $BIND"
}

case "$COMMAND" in
    install)   do_install ;;
    uninstall) do_uninstall ;;
    status)    do_status ;;
    *) fail "Usage: $0 {install|uninstall|status}" ;;
esac
